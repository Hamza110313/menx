export function getDistrictName(x: number, z: number): string {
  if (z > 214) return 'Pacific Ocean';
  if (z > 168 && x > 95) return 'Solaris Marina & Yacht Club';
  if (z > 168) return 'Solaris Oceanfront & Beach';
  if (x < -176 && z > -90 && z < 110) return 'Solaris International Airport';
  if (x < -150 && z <= -90) return 'Redwood Highlands Forest';
  if (x >= 190 && x <= 270 && z >= -160 && z <= -72) return 'Fort Solaris Army Camp';
  if (x > 180) return 'Solaris Badlands Desert';
  if (x >= -75 && x <= 75 && z >= -75 && z <= 75) return 'Downtown Core';
  if (x < -75 && z >= -75 && z <= 75) return 'Westside Commercial';
  if (x < -20 && z > 75) return 'Harbor Industrial Docks';
  if (x > 75 && z >= -10 && z <= 75) return 'Emerald Park';
  if (x > 75 && z < -75) return 'Midtown North & SBPD';
  if (z < -75) return 'Solaris Hills';
  return 'Solaris Bay';
}
